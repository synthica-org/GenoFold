"""
genofold.reconstruct.export
----------------------------
Export 3D genome structures to standard file formats.

Supported formats:
  .npy  — NumPy array (M, 3) of XYZ coordinates. Fast, lossless,
           used for downstream computation (scoring, explainability).

  .pdb  — Protein Data Bank format. Each genomic bin is written as
           a ATOM record with its XYZ coordinates. Opens directly in
           PyMOL, ChimeraX, VMD, and other molecular viewers.
           Ideal for conference figures and visualizations.

  .tsv  — Tab-separated table with bin_id, x, y, z, and confidence.
           Easy to load in R, pandas, or Excel for custom plots.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Optional

import numpy as np
import torch

logger = logging.getLogger(__name__)


def save_coordinates_npy(
    coords: torch.Tensor,
    path: str,
) -> None:
    """
    Save 3D coordinates as a NumPy .npy file.

    Parameters
    ----------
    coords:
        (M, 3) coordinate tensor.
    path:
        Output file path (e.g. 'outputs/structure.npy').
    """
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    arr = coords.detach().cpu().numpy().astype(np.float32)
    np.save(path, arr)
    logger.info(f"Saved coordinates (.npy): {path} | shape={arr.shape}")


def save_coordinates_pdb(
    coords: torch.Tensor,
    path: str,
    bin_size: int = 40_000,
    chrom: str = "chr1",
    confidence: Optional[torch.Tensor] = None,
    scale_factor: float = 10.0,
) -> None:
    """
    Save 3D genome structure as a PDB file.

    Each genomic bin is written as a CA (alpha-carbon) ATOM record.
    Bins are named sequentially as residues so molecular viewers
    can display the chain as a connected polymer (chromatin fiber).

    Parameters
    ----------
    coords:
        (M, 3) coordinate tensor in arbitrary units.
    path:
        Output .pdb file path.
    bin_size:
        Genomic bin size in bp (used to label residues).
    chrom:
        Chromosome name for REMARK header.
    confidence:
        Optional (M,) confidence scores [0, 1] per bin.
        Written to the B-factor column (standard PDB convention
        for per-residue confidence, e.g. AlphaFold uses this).
    scale_factor:
        Multiply coordinates by this factor before writing.
        PDB convention uses Angstroms; scale_factor=10 converts
        from nm-scale to Angstrom-scale.
    """
    Path(path).parent.mkdir(parents=True, exist_ok=True)

    xyz = coords.detach().cpu().numpy().astype(np.float64) * scale_factor
    M = xyz.shape[0]

    if confidence is not None:
        bfactors = confidence.detach().cpu().numpy().astype(np.float64)
        # Scale to [0, 100] for PDB B-factor convention
        bfactors = np.clip(bfactors * 100.0, 0.0, 100.0)
    else:
        bfactors = np.zeros(M)

    lines = []

    # Header
    lines.append(f"REMARK  GenoFold 3D Genome Structure")
    lines.append(f"REMARK  Chromosome: {chrom}")
    lines.append(f"REMARK  Bin size: {bin_size:,} bp")
    lines.append(f"REMARK  Number of bins: {M}")
    lines.append(f"REMARK  B-factor column = confidence score (0-100)")
    lines.append(f"REMARK  Generated by GenoFold (github.com/GenoFold)")

    # ATOM records
    for i in range(M):
        x, y, z = xyz[i]
        b = bfactors[i]
        res_num = i + 1
        # Genomic position label (start of bin in Mb)
        res_name = "BIN"

        # PDB ATOM format (strict column widths)
        line = (
            f"ATOM  {res_num:5d}  CA  {res_name} A{res_num:4d}    "
            f"{x:8.3f}{y:8.3f}{z:8.3f}"
            f"  1.00{b:6.2f}           C"
        )
        lines.append(line)

    # CONECT records — connect consecutive bins to show chromatin chain
    for i in range(1, M):
        lines.append(f"CONECT{i:5d}{i+1:5d}")

    lines.append("END")

    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")

    logger.info(f"Saved structure (.pdb): {path} | {M} bins, chrom={chrom}")


def save_coordinates_tsv(
    coords: torch.Tensor,
    path: str,
    bin_size: int = 40_000,
    chrom: str = "chr1",
    chrom_start: int = 0,
    confidence: Optional[torch.Tensor] = None,
) -> None:
    """
    Save 3D coordinates as a tab-separated table.

    Columns: bin_id, chrom, start, end, x, y, z, confidence

    Parameters
    ----------
    coords:
        (M, 3) coordinate tensor.
    path:
        Output .tsv file path.
    bin_size:
        Bin size in bp.
    chrom:
        Chromosome name.
    chrom_start:
        Chromosome start coordinate.
    confidence:
        Optional (M,) per-bin confidence scores.
    """
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    xyz = coords.detach().cpu().numpy()
    M = xyz.shape[0]

    conf_vals = (
        confidence.detach().cpu().numpy()
        if confidence is not None
        else np.ones(M)
    )

    with open(path, "w") as f:
        f.write("bin_id\tchrom\tstart\tend\tx\ty\tz\tconfidence\n")
        for i in range(M):
            start = chrom_start + i * bin_size
            end = start + bin_size
            f.write(
                f"{i}\t{chrom}\t{start}\t{end}\t"
                f"{xyz[i, 0]:.6f}\t{xyz[i, 1]:.6f}\t{xyz[i, 2]:.6f}\t"
                f"{conf_vals[i]:.6f}\n"
            )

    logger.info(f"Saved coordinates (.tsv): {path} | {M} bins")


def export_structure(
    coords: torch.Tensor,
    output_dir: str,
    prefix: str = "genofold_structure",
    bin_size: int = 40_000,
    chrom: str = "chr1",
    chrom_start: int = 0,
    confidence: Optional[torch.Tensor] = None,
) -> dict:
    """
    Export structure in all formats to an output directory.

    Parameters
    ----------
    coords:
        (M, 3) coordinate tensor.
    output_dir:
        Directory to write all output files.
    prefix:
        Filename prefix for all outputs.
    bin_size, chrom, chrom_start:
        Genomic coordinate metadata.
    confidence:
        Optional per-bin confidence scores.

    Returns
    -------
    dict
        Paths to each written file: {'npy': ..., 'pdb': ..., 'tsv': ...}
    """
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    paths = {
        "npy": str(Path(output_dir) / f"{prefix}.npy"),
        "pdb": str(Path(output_dir) / f"{prefix}.pdb"),
        "tsv": str(Path(output_dir) / f"{prefix}.tsv"),
    }

    save_coordinates_npy(coords, paths["npy"])
    save_coordinates_pdb(coords, paths["pdb"], bin_size, chrom, confidence)
    save_coordinates_tsv(coords, paths["tsv"], bin_size, chrom, chrom_start, confidence)

    logger.info(
        f"Structure exported to {output_dir}:\n"
        f"  .npy → {paths['npy']}\n"
        f"  .pdb → {paths['pdb']}\n"
        f"  .tsv → {paths['tsv']}"
    )
    return paths
